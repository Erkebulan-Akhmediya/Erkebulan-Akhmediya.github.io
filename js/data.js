/* Не разрываем математические выражения при переносе строки */
(function noBreakMath() {
  const fix = str => str.replace(/ ([·:×=]) /g, "\u00A0$1 ").replace(/(\d) ([·:×+−]) (?=\d)/g, "$1\u00A0$2\u00A0");
  const walk = o => {
    for (const k in o) {
      if (k === "svg") continue;
      if (typeof o[k] === "string") o[k] = fix(o[k]);
      else if (o[k] && typeof o[k] === "object") walk(o[k]);
    }
  };
  walk(TOPICS); walk(EXAM);
})();
